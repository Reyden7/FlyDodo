const TRANSLATIONS: Record<AppLanguage, TranslationTable> = { fr, en, es, de };

function interpolate(
  message: string,
  variables?: Record<string, string | number>,
): string {
  if (!variables) {
    return message;
  }

  return Object.entries(variables).reduce(
    (result, [name, value]) =>
      result.replaceAll(`{${name}}`, String(value)),
    message,
  );
}

function normalizeLanguage(value: unknown): AppLanguage {
  return APP_LANGUAGES.some(({ id }) => id === value)
    ? (value as AppLanguage)
    : 'fr';
}

let currentLanguage: AppLanguage =
  typeof window === 'undefined'
    ? 'fr'
    : normalizeLanguage(window.localStorage.getItem(LANGUAGE_STORAGE_KEY));

export function getAppLanguage(): AppLanguage {
  return currentLanguage;
}

export function setAppLanguage(language: AppLanguage): void {
  currentLanguage = normalizeLanguage(language);

  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, currentLanguage);
  } catch {
    // La langue reste active en mémoire lorsque le stockage est indisponible.
  }

  languageEvents.dispatchEvent(
    new CustomEvent<AppLanguage>('change', { detail: currentLanguage }),
  );
}

export function subscribeAppLanguage(
  listener: (language: AppLanguage) => void,
): () => void {
  const onChange = (event: Event): void => {
    listener((event as CustomEvent<AppLanguage>).detail);
  };

  languageEvents.addEventListener('change', onChange);
  return () => languageEvents.removeEventListener('change', onChange);
}

export function translate(
  key: string,
  variables?: Record<string, string | number>,
  language = currentLanguage,
): string {
  const localized = TRANSLATIONS[language] as Record<string, string>;
  const fallback = fr as Record<string, string>;
  return interpolate(localized[key] ?? fallback[key] ?? key, variables);
}
